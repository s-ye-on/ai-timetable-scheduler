-- Non-destructive local H2 baseline: create missing tables without removing data.
-- Existing tables are intentionally left untouched; Hibernate validation reports drift.

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(30) NOT NULL,
    email VARCHAR(30) NOT NULL UNIQUE,
    password VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token VARCHAR(512) NOT NULL UNIQUE,
    username VARCHAR(50) NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS preference (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE,
    preferred_time_range VARCHAR(20) NOT NULL,
    schedule_start_time TIME(6) NOT NULL,
    schedule_end_time TIME(6) NOT NULL,
    minimum_gap_minutes INTEGER NOT NULL,
    schedule_density VARCHAR(20) NOT NULL,
    deadline_timing VARCHAR(20) NOT NULL,
    customized BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_preference_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_preference_time_range CHECK (preferred_time_range IN ('MORNING', 'LUNCH', 'AFTERNOON', 'EVENING', 'ANYTIME')),
    CONSTRAINT ck_preference_density CHECK (schedule_density IN ('COMPACT', 'BALANCED', 'RELAXED')),
    CONSTRAINT ck_preference_deadline_timing CHECK (deadline_timing IN ('ASAP', 'BALANCED', 'NEAR_DEADLINE'))
);

CREATE TABLE IF NOT EXISTS timetable_slot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    subject_name VARCHAR(100) NOT NULL,
    day_of_week VARCHAR(10) NOT NULL,
    location VARCHAR(100),
    start_time TIME(6) NOT NULL,
    end_time TIME(6) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_timetable_slot_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_timetable_slot_day_of_week CHECK (day_of_week IN ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY'))
);

CREATE TABLE IF NOT EXISTS task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    title VARCHAR(100) NOT NULL,
    category VARCHAR(20) NOT NULL,
    duration_minutes INTEGER NOT NULL,
    preferred_date DATE,
    preferred_day_of_week VARCHAR(10),
    preferred_start_date DATE,
    preferred_end_date DATE,
    preferred_time_range VARCHAR(20),
    date_required BOOLEAN,
    time_required BOOLEAN,
    preferred_start_time TIME(0),
    deadline DATE,
    priority VARCHAR(10) NOT NULL,
    description VARCHAR(500),
    scheduled_start_at TIMESTAMP(6),
    scheduled_end_at TIMESTAMP(6),
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_task_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_task_category CHECK (category IN ('STUDY', 'ASSIGNMENT', 'APPOINTMENT', 'PERSONAL')),
    CONSTRAINT ck_task_preferred_day_of_week CHECK (preferred_day_of_week IS NULL OR preferred_day_of_week IN ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY')),
    CONSTRAINT ck_task_preferred_time_range CHECK (preferred_time_range IS NULL OR preferred_time_range IN ('MORNING', 'LUNCH', 'AFTERNOON', 'EVENING', 'ANYTIME')),
    CONSTRAINT ck_task_priority CHECK (priority IN ('HIGH', 'NORMAL', 'LOW')),
    CONSTRAINT ck_task_status CHECK (status IN ('UNSCHEDULED', 'SCHEDULED', 'COMPLETED', 'CANCELED'))
);

CREATE TABLE IF NOT EXISTS recommendation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    task_id BIGINT NOT NULL,
    recommended_start_at TIMESTAMP(6) NOT NULL,
    recommended_end_at TIMESTAMP(6) NOT NULL,
    rank INTEGER NOT NULL,
    score INTEGER NOT NULL,
    reason VARCHAR(500) NOT NULL,
    status VARCHAR(20) NOT NULL,
    google_event_id VARCHAR(255),
    match_type VARCHAR(32),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_recommendation_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_recommendation_task FOREIGN KEY (task_id) REFERENCES task (id),
    CONSTRAINT ck_recommendation_status CHECK (status IN ('PROPOSED', 'SELECTED', 'REJECTED', 'EXPIRED', 'SYNCED', 'SYNC_FAILED')),
    CONSTRAINT ck_recommendation_match_type CHECK (match_type IS NULL OR match_type IN ('EXACT', 'TIME_CHANGED', 'DATE_CHANGED', 'DATE_AND_TIME_CHANGED', 'GENERAL'))
);

CREATE TABLE IF NOT EXISTS calendar_token (
    calendar_token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE,
    access_token VARCHAR(2000) NOT NULL,
    refresh_token VARCHAR(2000),
    expires_at TIMESTAMP(6) NOT NULL,
    calendar_id VARCHAR(255) NOT NULL,
    CONSTRAINT fk_calendar_token_user FOREIGN KEY (user_id) REFERENCES users (id)
);
